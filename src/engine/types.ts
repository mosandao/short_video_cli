/**
 * galaxy-downloader-client engine 协议类型
 *
 * 引擎 = external/galaxy-downloader-client/engine/main.py（yt-dlp 封装）
 * 协议：stdin 写入一个 JSON 请求 → stdout 逐行输出 NDJSON 事件 → 处理完退出
 */

export interface EngineCookie {
    domain: string
    name: string
    value: string
    path?: string
    secure?: boolean
    /** Unix 秒级时间戳；<=0 或缺省表示会话 Cookie */
    expires?: number
}

/** 所有请求的公共字段 */
export interface EngineRequestBase {
    /** 登录态 Cookie（由调用方注入内存，凭据不落盘） */
    cookies?: EngineCookie[]
    /** 附加 HTTP 头（Referer / Authorization 等） */
    headers?: Record<string, string>
    /** ffmpeg 路径（merge / 音频提取 / 封面嵌入需要） */
    ffmpeg?: string
    /** node 路径（yt-dlp 解析部分平台需要 JS 运行时） */
    node?: string
    /** socket 超时秒数（默认 30） */
    timeout?: number
    /** 重试次数（默认 3） */
    retries?: number
    /** 限速（yt-dlp ratelimit 格式，如 "2M"） */
    speedLimit?: string
    /** 语言环境: zh / zh-tw / ja / en（影响 YouTube 标题语言） */
    locale?: string
}

export interface EngineVersionRequest extends EngineRequestBase {
    operation: 'version' | 'kernel-check'
}

export interface EngineExtractRequest extends EngineRequestBase {
    operation: 'extract'
    url: string
    /** 列表扁平枚举（默认 true，速度快；单视频解析格式表时传 false） */
    flat?: boolean
}

export interface EngineDownloadRequest extends EngineRequestBase {
    operation: 'download'
    url: string
    /** yt-dlp 输出模板，如 /path/%(title)s.%(ext)s */
    output: string
    /** yt-dlp 格式选择器，如 bv*+ba/b */
    format?: string
    /** 播放列表条目选择（yt-dlp playlist_items 语法，如 "1,3-5"） */
    entry?: string
    playliststart?: number
    playlistend?: number
    /** 纯音频模式（FFmpegExtractAudio 后处理器） */
    audioOnly?: boolean
    /** 音频容器: mp3 / m4a / best ... */
    audioFormat?: string
    audioFormatId?: string
    audioLanguage?: string
    /** 字幕: 'off' | 'file'（另存文件） */
    subtitles?: 'off' | 'file'
    subtitleLanguages?: string
    subtitleAutoGenerated?: boolean
    saveThumbnail?: boolean
    embedThumbnail?: boolean
    workMode?: 'download' | 'edit'
}

export interface EngineCaptionsRequest extends EngineRequestBase {
    operation: 'captions'
    url: string
    /** 字幕文件输出模板 */
    output: string
    captionLanguages?: string[]
    subtitleAutoGenerated?: boolean
}

export type EngineRequest =
    | EngineVersionRequest
    | EngineExtractRequest
    | EngineDownloadRequest
    | EngineCaptionsRequest

/** stdout NDJSON 事件 */
export type EngineEvent =
    | { kind: 'log'; message: string }
    | { kind: 'progress'; status: string; downloaded: number; total?: number; speed?: number; eta?: number }
    | { kind: 'processing'; status: string; progress: number }
    | { kind: 'original'; result: { file: string } }
    | { kind: 'error'; message: string; code?: string }
    | { kind: 'result'; result: unknown }
    | { kind: string; [key: string]: unknown }

export interface EngineRunOutcome {
    ok: boolean
    /** result 事件的负载（各 operation 不同） */
    result?: unknown
    /** error 事件或进程异常信息 */
    error?: string
    code?: string
}

/** extract 的 result：yt-dlp sanitize_info 输出（松散类型，按需取字段） */
export interface YtDlpInfo {
    _type?: string
    id?: string
    title?: string
    description?: string
    uploader?: string
    uploader_id?: string
    channel?: string
    duration?: number
    thumbnail?: string
    webpage_url?: string
    original_url?: string
    extractor?: string
    extractor_key?: string
    upload_date?: string
    timestamp?: number
    view_count?: number
    like_count?: number
    playlist_count?: number
    playlist_title?: string
    channel_follower_count?: number
    formats?: YtDlpFormat[]
    entries?: YtDlpInfo[]
    [key: string]: unknown
}

export interface YtDlpFormat {
    format_id?: string
    ext?: string
    height?: number
    width?: number
    fps?: number
    vcodec?: string
    acodec?: string
    filesize?: number
    filesize_approx?: number
    tbr?: number
    format_note?: string
    [key: string]: unknown
}

/** download 的 result */
export interface EngineDownloadResult {
    files: string[]
    originalFiles?: string[]
    processedFiles?: string[]
}

/** captions 的 result */
export interface EngineCaptionsResult {
    tracks: Array<{ language: string; file: string }>
}

/** version / kernel-check 的 result */
export interface EngineVersionResult {
    version: string
}
